import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score
from sklearn.decomposition import PCA

# Load dataset
url = "https://raw.githubusercontent.com/npradaschnor/Pima-Indians-Diabetes-Dataset/master/diabetes.csv"

df = pd.read_csv(url)

# Display first 5 rows
df.head()

# Select features for clustering
features = [
    'Pregnancies',
    'Glucose',
    'BloodPressure',
    'SkinThickness',
    'Insulin',
    'BMI',
    'DiabetesPedigreeFunction',
    'Age'
]

X = df[features].copy()

# Check missing values
print("Missing values:")
print(X.isnull().sum())

# Check zero values
print("\nZero values:")
print((X == 0).sum())

# Replace invalid zero values with NaN
invalid_columns = [
    'Glucose',
    'BloodPressure',
    'SkinThickness',
    'Insulin',
    'BMI'
]

X[invalid_columns] = X[invalid_columns].replace(0, np.nan)

# Replace missing values with median
X = X.fillna(X.median())

# Check again
print("Missing values after treatment:")
print(X.isnull().sum())

print("\nFirst 5 rows after preprocessing:")
print(X.head())

# Standardize the features
scaler = StandardScaler()

X_scaled = scaler.fit_transform(X)

# Convert back to DataFrame for easy viewing
X_scaled = pd.DataFrame(X_scaled, columns=features)

# Display first 5 standardized rows
X_scaled.head()

# Calculate WCSS for different numbers of clusters
wcss = []

for k in range(1, 11):
    kmeans = KMeans(n_clusters=k, random_state=42, n_init=10)
    kmeans.fit(X_scaled)
    wcss.append(kmeans.inertia_)

# Plot Elbow Curve
plt.figure(figsize=(8, 5))
plt.plot(range(1, 11), wcss, marker='o')

plt.xlabel("Number of Clusters (k)")
plt.ylabel("WCSS")
plt.title("Elbow Method for Optimal Number of Clusters")
plt.xticks(range(1, 11))
plt.grid(True)
plt.show()

# Apply K-Means clustering
kmeans = KMeans(n_clusters=2, random_state=42, n_init=10)

# Fit the model and assign clusters
clusters = kmeans.fit_predict(X_scaled)

# Add cluster labels to the original dataframe
df['Cluster'] = clusters

# Display cluster assignments
print("Cluster assignments:")
print(df[['Outcome', 'Cluster']].head(10))

# Count observations in each cluster
print("Number of patients in each cluster:")
print(df['Cluster'].value_counts().sort_index())

# Calculate Silhouette Score
sil_score = silhouette_score(X_scaled, clusters)

print("Silhouette Score:", sil_score)

# Apply PCA to reduce the data to 2 dimensions
pca = PCA(n_components=2)

X_pca = pca.fit_transform(X_scaled)

# Create a DataFrame for PCA results
pca_df = pd.DataFrame(
    X_pca,
    columns=['Principal Component 1', 'Principal Component 2']
)

# Add cluster labels
pca_df['Cluster'] = clusters

# Display first 5 rows
pca_df.head()

# Explained variance by each principal component
print("Explained variance ratio:")
print(pca.explained_variance_ratio_)

print("\nTotal variance explained by 2 components:")
print(pca.explained_variance_ratio_.sum())

plt.figure(figsize=(8, 6))

sns.scatterplot(
    data=pca_df,
    x='Principal Component 1',
    y='Principal Component 2',
    hue='Cluster',
    palette='Set1',
    s=70
)

plt.title("K-Means Clusters Visualized Using PCA")
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.legend(title="Cluster")
plt.grid(True)
plt.show()

# Compare clusters with actual diabetes outcome
cluster_outcome = pd.crosstab(
    df['Cluster'],
    df['Outcome']
)

print("Cluster vs Diabetes Outcome:")
print(cluster_outcome)

# Percentage distribution of diabetes outcome within each cluster
cluster_percentage = pd.crosstab(
    df['Cluster'],
    df['Outcome'],
    normalize='index'
) * 100

print("Percentage distribution:")
print(cluster_percentage.round(2))

plt.figure(figsize=(8, 6))

sns.scatterplot(
    data=pca_df,
    x='Principal Component 1',
    y='Principal Component 2',
    hue=df['Outcome'],
    style=df['Cluster'],
    palette='Set1',
    s=80
)

plt.title("PCA Visualization: Diabetes Outcome and K-Means Clusters")
plt.xlabel("Principal Component 1")
plt.ylabel("Principal Component 2")
plt.legend(title="Diabetes Outcome / Cluster")
plt.grid(True)
plt.show()

# Calculate mean values of features for each cluster
cluster_means = df.groupby('Cluster')[features].mean()

print("Mean feature values for each cluster:")
print(cluster_means.round(2))

plt.figure(figsize=(12, 6))

sns.heatmap(
    cluster_means,
    annot=True,
    fmt='.2f',
    cmap='coolwarm'
)

plt.title("Average Feature Values Across Clusters")
plt.xlabel("Features")
plt.ylabel("Cluster")
plt.show()

print("========== FINAL RESULTS ==========")

print("\nNumber of clusters:", 2)

print("\nCluster Size:")
print(df['Cluster'].value_counts().sort_index())

print("\nSilhouette Score:")
print(round(sil_score, 4))

print("\nPCA Explained Variance:")
print(pca.explained_variance_ratio_.round(4))

print("\nTotal Variance Explained by 2 PCs:")
print(round(pca.explained_variance_ratio_.sum(), 4))

print("\nCluster vs Outcome:")
print(pd.crosstab(df['Cluster'], df['Outcome']))